 sender_id VARCHAR(128) NOT NULL,
 effort VARCHAR(16) NOT NULL DEFAULT 'auto',
 style VARCHAR(16) NOT NULL DEFAULT 'concise',
 PRIMARY KEY(topic_id,sender_id)
