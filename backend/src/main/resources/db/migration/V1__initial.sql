CREATE TABLE topic (
    id VARCHAR(64) PRIMARY KEY,
    tenant_id VARCHAR(128) NOT NULL,
    app_id VARCHAR(128) NOT NULL,
    chat_id VARCHAR(128) NOT NULL,
    external_key VARCHAR(256) NOT NULL,
    UNIQUE (tenant_id, app_id, chat_id, external_key)
);
CREATE TABLE ingress (
    id VARCHAR(64) PRIMARY KEY,
    tenant_id VARCHAR(128) NOT NULL,
    app_id VARCHAR(128) NOT NULL,
    event_id VARCHAR(128) NOT NULL,
    message_id VARCHAR(128) NOT NULL,
    task_id VARCHAR(64),
    created_at BIGINT NOT NULL,
    UNIQUE (tenant_id, app_id, event_id),
    UNIQUE (tenant_id, app_id, message_id)
);
CREATE TABLE task (
    id VARCHAR(64) PRIMARY KEY,
    position BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tenant_id VARCHAR(128) NOT NULL,
    topic_id VARCHAR(64) NOT NULL REFERENCES topic(id),
    sender_id VARCHAR(128) NOT NULL,
    message_id VARCHAR(128) NOT NULL,
    prompt TEXT NOT NULL,
    status VARCHAR(32) NOT NULL,
    result TEXT,
    error_code VARCHAR(64),
    model VARCHAR(128),
    usage_json TEXT,
    lease_token VARCHAR(64),
    lease_until BIGINT,
    deadline BIGINT,
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE INDEX task_queue ON task(status, created_at);
CREATE INDEX task_topic ON task(topic_id, created_at);
CREATE TABLE run_event (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id VARCHAR(64) NOT NULL REFERENCES task(id),
    type VARCHAR(32) NOT NULL,
    detail TEXT NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE TABLE delivery (
    id VARCHAR(64) PRIMARY KEY,
    position BIGINT GENERATED BY DEFAULT AS IDENTITY,
    task_id VARCHAR(64),
    reply_to VARCHAR(128) NOT NULL,
    content TEXT NOT NULL,
    status VARCHAR(32) NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    lease_token VARCHAR(64),
    available_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    error_code VARCHAR(64),
    platform_message_id VARCHAR(128)
);
CREATE INDEX delivery_queue ON delivery(status, available_at);
